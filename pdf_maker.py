"""
pdf_maker.py
------------
Converts the Markdown notes generated by the LLM into a nicely formatted PDF.

Usage:
    from pdf_maker import create_pdf
    pdf_bytes = create_pdf(notes_markdown, title="Study Notes")

Supported Markdown:
    # / ## / ### headings, paragraphs, **bold**, *italic*, `inline code`,
    - / * / + bullet lists (nested), 1. numbered lists, > block quotes,
    --- horizontal rules, ``` code blocks ```, and | tables |.

Requires:  pip install reportlab
"""

import os
import re
from datetime import datetime
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import cm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    Paragraph,
    Preformatted,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

# Theme colours (same teal as the app header)
PRIMARY = colors.HexColor("#00695c")
ACCENT = colors.HexColor("#4db6ac")
LIGHT_BG = colors.HexColor("#e0f2f1")
TEXT = colors.HexColor("#1b1b1b")
GREY = colors.HexColor("#6b7a6b")


# ---------------------------------------------------------------------------
# Fonts
# ---------------------------------------------------------------------------
# Built-in PDF fonts (Helvetica) only support basic Latin characters. If a
# Unicode TrueType font is found we use it, so symbols like  ≤  ≥  →  α  β
# (common in ML notes) render properly.
# Tip: put DejaVuSans.ttf, DejaVuSans-Bold.ttf, DejaVuSans-Oblique.ttf and
# DejaVuSans-BoldOblique.ttf inside a "fonts" folder next to this file to be
# sure it works on every machine.

_HERE = os.path.dirname(os.path.abspath(__file__))

_FONT_CANDIDATES = [
    # (regular, bold, italic, bold-italic)
    tuple(os.path.join(_HERE, "fonts", f) for f in (
        "DejaVuSans.ttf", "DejaVuSans-Bold.ttf",
        "DejaVuSans-Oblique.ttf", "DejaVuSans-BoldOblique.ttf")),
    tuple(os.path.join("/usr/share/fonts/truetype/dejavu", f) for f in (
        "DejaVuSans.ttf", "DejaVuSans-Bold.ttf",
        "DejaVuSans-Oblique.ttf", "DejaVuSans-BoldOblique.ttf")),
    tuple(os.path.join("C:\\Windows\\Fonts", f) for f in (
        "arial.ttf", "arialbd.ttf", "ariali.ttf", "arialbi.ttf")),
    tuple(os.path.join("/Library/Fonts", f) for f in (
        "Arial.ttf", "Arial Bold.ttf", "Arial Italic.ttf", "Arial Bold Italic.ttf")),
]

_font_cache = None


def _setup_fonts():
    """Register a Unicode font family once. Returns (base, mono, is_unicode)."""
    global _font_cache
    if _font_cache:
        return _font_cache

    for paths in _FONT_CANDIDATES:
        if all(os.path.exists(p) for p in paths):
            try:
                name = "NotesFont"
                for suffix, path in zip(("", "-Bold", "-Italic", "-BoldItalic"), paths):
                    pdfmetrics.registerFont(TTFont(name + suffix, path))
                pdfmetrics.registerFontFamily(
                    name,
                    normal=name,
                    bold=name + "-Bold",
                    italic=name + "-Italic",
                    boldItalic=name + "-BoldItalic",
                )
                _font_cache = (name, "Courier", True)
                return _font_cache
            except Exception:
                continue

    _font_cache = ("Helvetica", "Courier", False)
    return _font_cache


# ---------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------
_EMOJI_RE = re.compile("[\U00010000-\U0010FFFF\u200d\ufe0f\u2600-\u27bf]")


def _clean(text, unicode_ok):
    """Remove emojis; if only basic fonts are available, drop unsupported chars."""
    text = _EMOJI_RE.sub("", text)
    if not unicode_ok:
        text = (
            text.replace("\u2019", "'").replace("\u2018", "'")
            .replace("\u201c", '"').replace("\u201d", '"')
            .replace("\u2013", "-").replace("\u2014", "-")
            .replace("\u2192", "->").replace("\u2264", "<=").replace("\u2265", ">=")
        )
        text = text.encode("cp1252", errors="replace").decode("cp1252")
    return text


def _inline(text, unicode_ok):
    """Convert inline Markdown (bold, italic, code) to ReportLab mini-HTML."""
    text = _clean(text, unicode_ok)

    # Protect inline code first so its content is not touched by bold/italic.
    codes = []

    def _stash(match):
        codes.append(match.group(1))
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", _stash, text)
    text = escape(text)  # &, <, >

    text = re.sub(r"\*\*\*(.+?)\*\*\*", r"<b><i>\1</i></b>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"__(.+?)__", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<i>\1</i>", text)

    def _restore(match):
        code = escape(codes[int(match.group(1))])
        return f'<font name="Courier" backColor="#eef3ee" color="#00695c">{code}</font>'

    return re.sub(r"\x00(\d+)\x00", _restore, text)


# ---------------------------------------------------------------------------
# Styles
# ---------------------------------------------------------------------------
def _build_styles(base, mono):
    body = ParagraphStyle(
        "Body", fontName=base, fontSize=10.5, leading=15,
        textColor=TEXT, alignment=TA_LEFT, spaceAfter=6,
    )
    return {
        "body": body,
        "h1": ParagraphStyle(
            "H1", parent=body, fontName=base + "-Bold",
            fontSize=22, leading=27, textColor=PRIMARY, spaceBefore=4, spaceAfter=10,
        ),
        "h2": ParagraphStyle(
            "H2", parent=body, fontName=base + "-Bold",
            fontSize=15, leading=19, textColor=PRIMARY, spaceBefore=14, spaceAfter=6,
        ),
        "h3": ParagraphStyle(
            "H3", parent=body, fontName=base + "-Bold",
            fontSize=12.5, leading=16, textColor=colors.HexColor("#00897b"),
            spaceBefore=10, spaceAfter=4,
        ),
        "bullet": ParagraphStyle("Bullet", parent=body, spaceAfter=3),
        "quote": ParagraphStyle(
            "Quote", parent=body, leftIndent=14, textColor=GREY,
            borderPadding=(4, 4, 4, 8), backColor=LIGHT_BG,
        ),
        "code": ParagraphStyle(
            "Code", fontName=mono, fontSize=9, leading=12,
            backColor=colors.HexColor("#f3f6f3"), borderPadding=6,
            leftIndent=6, rightIndent=6, spaceAfter=8,
        ),
        "cell": ParagraphStyle("Cell", parent=body, fontSize=9.5, leading=12.5, spaceAfter=0),
        "cell_head": ParagraphStyle(
            "CellHead", parent=body, fontSize=9.5, leading=12.5, spaceAfter=0,
            textColor=colors.white,
            fontName=base + "-Bold",
        ),
    }


# ---------------------------------------------------------------------------
# Markdown -> flowables
# ---------------------------------------------------------------------------
_BULLET_RE = re.compile(r"^(\s*)[-*+]\s+(.*)$")
_NUMBER_RE = re.compile(r"^(\s*)(\d+)[.)]\s+(.*)$")
_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_TABLE_SEP_RE = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")


def _split_row(line):
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def _make_table(rows, styles, width, unicode_ok):
    ncols = max(len(r) for r in rows)
    data = []
    for i, row in enumerate(rows):
        row = row + [""] * (ncols - len(row))
        style = styles["cell_head"] if i == 0 else styles["cell"]
        data.append([Paragraph(_inline(c, unicode_ok), style) for c in row])

    table = Table(data, colWidths=[width / ncols] * ncols, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT_BG]),
        ("GRID", (0, 0), (-1, -1), 0.5, ACCENT),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
    ]))
    return table


def _markdown_to_flowables(md, styles, width, unicode_ok):
    flow = []
    lines = md.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    i = 0
    para_buf = []

    def flush_paragraph():
        if para_buf:
            text = " ".join(s.strip() for s in para_buf)
            flow.append(Paragraph(_inline(text, unicode_ok), styles["body"]))
            para_buf.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Blank line -> ends paragraph
        if not stripped:
            flush_paragraph()
            i += 1
            continue

        # Fenced code block
        if stripped.startswith("```"):
            flush_paragraph()
            i += 1
            code_lines = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code_lines.append(_clean(lines[i], unicode_ok))
                i += 1
            i += 1  # closing fence
            flow.append(Preformatted("\n".join(code_lines), styles["code"]))
            continue

        # Horizontal rule
        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", stripped):
            flush_paragraph()
            flow.append(Spacer(1, 4))
            flow.append(HRFlowable(width="100%", thickness=0.8, color=ACCENT))
            flow.append(Spacer(1, 4))
            i += 1
            continue

        # Heading
        m = _HEADING_RE.match(stripped)
        if m:
            flush_paragraph()
            level = min(len(m.group(1)), 3)
            para = Paragraph(_inline(m.group(2), unicode_ok), styles[f"h{level}"])
            if level == 1:
                flow.append(para)
                flow.append(HRFlowable(width="100%", thickness=1.5, color=PRIMARY, spaceAfter=8))
            else:
                flow.append(para)
            i += 1
            continue

        # Table
        if stripped.startswith("|") and i + 1 < len(lines) and _TABLE_SEP_RE.match(lines[i + 1]):
            flush_paragraph()
            rows = [_split_row(stripped)]
            i += 2
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_split_row(lines[i]))
                i += 1
            flow.append(_make_table(rows, styles, width, unicode_ok))
            flow.append(Spacer(1, 8))
            continue

        # Block quote
        if stripped.startswith(">"):
            flush_paragraph()
            quote_lines = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                quote_lines.append(lines[i].strip().lstrip(">").strip())
                i += 1
            flow.append(Paragraph(_inline(" ".join(quote_lines), unicode_ok), styles["quote"]))
            continue

        # Bullet list item
        m = _BULLET_RE.match(line.expandtabs(4))
        if m:
            flush_paragraph()
            level = len(m.group(1)) // 2
            style = ParagraphStyle(
                f"B{level}", parent=styles["bullet"],
                leftIndent=16 + level * 16, bulletIndent=4 + level * 16,
            )
            glyph = "\u2022" if level == 0 else "\u2013"
            if not unicode_ok:
                glyph = "-" if level else "\u2022"
            flow.append(Paragraph(_inline(m.group(2), unicode_ok), style, bulletText=glyph))
            i += 1
            continue

        # Numbered list item
        m = _NUMBER_RE.match(line.expandtabs(4))
        if m:
            flush_paragraph()
            level = len(m.group(1)) // 2
            style = ParagraphStyle(
                f"N{level}", parent=styles["bullet"],
                leftIndent=20 + level * 16, bulletIndent=2 + level * 16,
            )
            flow.append(Paragraph(_inline(m.group(3), unicode_ok), style, bulletText=f"{m.group(2)}."))
            i += 1
            continue

        # Normal text
        para_buf.append(line)
        i += 1

    flush_paragraph()
    return flow


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------
def create_pdf(notes, title="Study Notes", source_url=None):
    """
    Convert Markdown notes to a PDF.

    Args:
        notes (str):        Markdown text generated by the LLM.
        title (str):        Title stored in the PDF metadata / footer.
        source_url (str):   Optional YouTube URL printed under the notes.

    Returns:
        bytes: the PDF file content (pass it to st.download_button).
    """
    if not notes or not notes.strip():
        raise ValueError("No notes available to convert to PDF.")

    base, mono, unicode_ok = _setup_fonts()
    styles = _build_styles(base, mono)

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm,
        title=_clean(title, unicode_ok),
        author="Note Maker",
    )
    width = doc.width

    story = _markdown_to_flowables(notes, styles, width, unicode_ok)

    if source_url:
        story.append(Spacer(1, 14))
        story.append(HRFlowable(width="100%", thickness=0.5, color=ACCENT))
        story.append(Spacer(1, 4))
        story.append(Paragraph(
            f"Source: {escape(source_url)}",
            ParagraphStyle("Src", parent=styles["body"], fontSize=9, textColor=GREY),
        ))

    footer_font = base
    date_str = datetime.now().strftime("%d %b %Y")

    def _footer(canvas, document):
        canvas.saveState()
        canvas.setFont(footer_font, 8.5)
        canvas.setFillColor(GREY)
        canvas.drawString(2 * cm, 1.1 * cm, f"Generated by Note Maker  |  {date_str}")
        canvas.drawRightString(A4[0] - 2 * cm, 1.1 * cm, f"Page {document.page}")
        canvas.setStrokeColor(ACCENT)
        canvas.setLineWidth(0.6)
        canvas.line(2 * cm, 1.5 * cm, A4[0] - 2 * cm, 1.5 * cm)
        canvas.restoreState()

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


